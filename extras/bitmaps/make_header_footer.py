#!/usr/bin/env python3
"""
make_header_footer.py - the pre-rendered header and footer images for the
TerminalHeaderFooter example, as RGB565 arrays.

  python3 make_header_footer.py DejaVuSans-Bold.ttf DejaVuSans.ttf \
      ../../examples/TerminalHeaderFooter/bitmaps.h

Both are 320 pixels wide, the widest panel in the family.  The sketch draws
them centered, so on a 240-wide panel 40 pixels drop off each side; keep
anything that matters inside the middle 240.  Needs Pillow.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, HH, FH = 320, 48, 32

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def header(bold, regular):
    im = Image.new('RGB', (W, HH))
    d = ImageDraw.Draw(im)
    for x in range(W):                       # navy to teal
        t = x / (W - 1)
        d.line([(x, 0), (x, HH - 1)], fill=(int(10 + 10 * t), int(30 + 110 * t), int(90 + 60 * t)))
    d.line([(0, HH - 2), (W, HH - 2)], fill=(255, 200, 0), width=2)
    d.text((W // 2, 20), 'CYD TERMINAL', font=ImageFont.truetype(bold, 22), fill='white', anchor='mm')
    d.text((W // 2, 38), 'frozen header  •  scrolling text below',
           font=ImageFont.truetype(regular, 11), fill=(200, 230, 255), anchor='mm')
    return im

def footer(regular):
    im = Image.new('RGB', (W, FH), (32, 32, 40))
    d = ImageDraw.Draw(im)
    d.line([(0, 0), (W, 0)], fill=(255, 200, 0), width=2)
    # 40..280 is the part a 240-wide panel shows.
    d.text((46, 17), 'activity', font=ImageFont.truetype(regular, 12), fill=(180, 180, 190), anchor='lm')
    d.rectangle([109, 11, 271, 23], outline=(120, 120, 130))   # the bar's frame
    return im

def c_array(name, im):
    px = [rgb565(*p) for p in im.getdata()]
    out = [f'// {im.width} x {im.height} RGB565, row by row.',
           f'static const uint16_t {name}[{im.width * im.height}] = {{']
    for k in range(0, len(px), 16):
        out.append('    ' + ', '.join(f'0x{v:04X}' for v in px[k:k + 16]) + ',')
    out.append('};')
    return '\n'.join(out) + '\n'

bold, regular, out = sys.argv[1:4]
with open(out, 'w') as f:
    f.write('// Generated by extras/bitmaps/make_header_footer.py - do not edit.\n'
            '// Text set in DejaVu Sans (Bitstream Vera license).\n#pragma once\n#include <stdint.h>\n\n')
    f.write(f'#define HEADER_W {W}\n#define HEADER_H {HH}\n#define FOOTER_W {W}\n#define FOOTER_H {FH}\n')
    f.write('// The footer\'s activity bar: inside the frame drawn into the image.\n'
            '#define BAR_X 110\n#define BAR_Y 12\n#define BAR_W 161\n#define BAR_H 11\n\n')
    f.write(c_array('kHeader', header(bold, regular)))
    f.write('\n')
    f.write(c_array('kFooter', footer(regular)))
